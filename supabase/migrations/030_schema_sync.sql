-- 030: Sincroniza el repositorio con el esquema real de producción.
-- Estas tablas/columnas existen en Supabase (se crearon a mano) pero no estaban en
-- ninguna migración. Verificado contra producción el 2026-11-12:
--   tasks: description, novedad, parent_task_id, linked_note_id
--   habits: tag (categoría del hábito)
--   board_shares (board_id, shared_with)
--   task_comments (id, task_id, user_id, content, created_at)
--
-- Es seguro ejecutarlo en la base actual: todo usa "if not exists" y la seguridad
-- (RLS y políticas) solo se crea cuando la tabla es nueva, así que no cambia nada
-- de lo que ya existe en producción.

-- 1) Columnas de tareas ------------------------------------------------------
alter table public.tasks add column if not exists description text;
alter table public.tasks add column if not exists novedad text;
alter table public.tasks
  add column if not exists parent_task_id bigint references public.tasks (id) on delete cascade;
alter table public.tasks
  add column if not exists linked_note_id uuid references public.notes (id) on delete set null;

create index if not exists tasks_parent_task_id_idx on public.tasks (parent_task_id);

-- 1b) Categoría de los hábitos -------------------------------------------------
alter table public.habits add column if not exists tag text default 'General';

-- 2) Tableros de tareas compartidos ------------------------------------------
do $$
declare
  is_new boolean := to_regclass('public.board_shares') is null;
begin
  create table if not exists public.board_shares (
    board_id bigint not null references public.boards (id) on delete cascade,
    shared_with uuid not null references public.profiles (id) on delete cascade,
    primary key (board_id, shared_with)
  );

  if is_new then
    create index board_shares_shared_with_idx on public.board_shares (shared_with);

    alter table public.board_shares enable row level security;

    -- Lo ven el dueño del tablero y la persona invitada
    create policy "board_shares_select" on public.board_shares for select using (
      auth.uid() = shared_with
      or exists (select 1 from public.boards b where b.id = board_id and b.user_id = auth.uid())
    );
    -- Solo el dueño del tablero comparte o deja de compartir
    create policy "board_shares_insert" on public.board_shares for insert with check (
      exists (select 1 from public.boards b where b.id = board_id and b.user_id = auth.uid())
    );
    create policy "board_shares_update" on public.board_shares for update using (
      exists (select 1 from public.boards b where b.id = board_id and b.user_id = auth.uid())
    );
    -- El dueño quita a cualquiera; el invitado puede salirse
    create policy "board_shares_delete" on public.board_shares for delete using (
      auth.uid() = shared_with
      or exists (select 1 from public.boards b where b.id = board_id and b.user_id = auth.uid())
    );
  end if;
end;
$$;

-- 3) Comentarios de tareas ---------------------------------------------------
do $$
declare
  is_new boolean := to_regclass('public.task_comments') is null;
begin
  create table if not exists public.task_comments (
    id bigint generated by default as identity primary key,
    task_id bigint not null references public.tasks (id) on delete cascade,
    user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
    content text not null,
    created_at timestamptz not null default now()
  );

  if is_new then
    create index task_comments_task_id_idx on public.task_comments (task_id);

    alter table public.task_comments enable row level security;

    -- Comentan y leen quienes ven la tarea (dueño o con quien se compartió)
    create policy "task_comments_select" on public.task_comments for select using (
      exists (select 1 from public.tasks t where t.id = task_id)
    );
    create policy "task_comments_insert" on public.task_comments for insert with check (
      auth.uid() = user_id
      and exists (select 1 from public.tasks t where t.id = task_id)
    );
    -- Cada quien borra solo sus comentarios
    create policy "task_comments_delete" on public.task_comments for delete using (
      auth.uid() = user_id
    );
  end if;
end;
$$;
