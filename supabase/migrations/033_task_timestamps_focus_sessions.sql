-- 033: Datos para análisis.
--
-- 1) tasks.created_at y tasks.completed_at
--    Permiten medir cuánto tarda una tarea en completarse.
--    Las tareas que ya existían quedan con NULL ("fecha desconocida"): no se inventan fechas.
--    completed_at lo mantiene un trigger, así funciona igual desde Hoy, el tablero,
--    el arrastre entre columnas o cualquier otro camino que cambie is_completed.
--
-- 2) public.focus_sessions
--    Una fila por fase de Pomodoro terminada (completa o interrumpida).
--
-- Es idempotente: se puede ejecutar más de una vez.

-- 1) Tareas -----------------------------------------------------------------------------
alter table public.tasks add column if not exists created_at timestamptz;
alter table public.tasks alter column created_at set default now();
alter table public.tasks add column if not exists completed_at timestamptz;

create or replace function public.set_task_completed_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  if tg_op = 'INSERT' then
    new.completed_at := case when new.is_completed then coalesce(new.completed_at, now()) end;
  elsif new.is_completed is distinct from old.is_completed then
    new.completed_at := case when new.is_completed then now() end;
  else
    new.completed_at := old.completed_at;  -- no se puede editar a mano
  end if;
  return new;
end;
$$;

drop trigger if exists tasks_set_completed_at on public.tasks;
create trigger tasks_set_completed_at
  before insert or update on public.tasks
  for each row execute function public.set_task_completed_at();

create index if not exists tasks_completed_at_idx on public.tasks (completed_at);

-- 2) Sesiones de enfoque ----------------------------------------------------------------
create table if not exists public.focus_sessions (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  phase text not null check (phase in ('focus', 'break')),
  started_at timestamptz not null,
  ended_at timestamptz not null,
  planned_seconds integer not null check (planned_seconds > 0),
  actual_seconds integer not null check (actual_seconds >= 0),
  completed boolean not null,
  -- Referencia suave: si la tarea se borra, la sesión se conserva para el histórico.
  task_id bigint,
  created_at timestamptz not null default now(),
  constraint focus_sessions_time_order check (ended_at >= started_at),
  -- Evita duplicados (dos pestañas abiertas o reintentos sin conexión).
  constraint focus_sessions_user_started_key unique (user_id, started_at)
);

alter table public.focus_sessions enable row level security;

drop policy if exists "focus_sessions_select_own" on public.focus_sessions;
drop policy if exists "focus_sessions_insert_own" on public.focus_sessions;
drop policy if exists "focus_sessions_delete_own" on public.focus_sessions;

create policy "focus_sessions_select_own" on public.focus_sessions for select to authenticated
  using (user_id = auth.uid());
create policy "focus_sessions_insert_own" on public.focus_sessions for insert to authenticated
  with check (user_id = auth.uid());
create policy "focus_sessions_delete_own" on public.focus_sessions for delete to authenticated
  using (user_id = auth.uid());
