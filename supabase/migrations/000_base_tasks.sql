-- 000: Tabla base de tareas.
-- La tabla public.tasks se creó a mano en Supabase antes de que existieran migraciones,
-- pero 001_tags.sql y las siguientes ya la modifican. Este archivo la reconstruye para
-- poder montar una base de datos nueva desde cero.
--
-- Es seguro ejecutarlo en la base actual: si la tabla ya existe no cambia nada
-- (ni columnas, ni RLS, ni políticas).

do $$
declare
  is_new boolean := to_regclass('public.tasks') is null;
begin
  create table if not exists public.tasks (
    id bigint generated by default as identity primary key,
    user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
    title text not null,
    is_completed boolean not null default false,
    date date,
    order_index integer default 0
  );

  if is_new then
    create index tasks_user_id_idx on public.tasks (user_id);
    create index tasks_date_idx on public.tasks (date);

    alter table public.tasks enable row level security;

    create policy "Users can select own tasks"
      on public.tasks for select using (auth.uid() = user_id);
    create policy "Users can insert own tasks"
      on public.tasks for insert with check (auth.uid() = user_id);
    create policy "Users can update own tasks"
      on public.tasks for update using (auth.uid() = user_id) with check (auth.uid() = user_id);
    create policy "Users can delete own tasks"
      on public.tasks for delete using (auth.uid() = user_id);
  end if;
end;
$$;
