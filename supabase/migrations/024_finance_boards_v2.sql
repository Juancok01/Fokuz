  with check (public.finance_can_access_board(board_id));

-- 4) Resumen de tableros (saldo actual, ingresos/gastos del mes) ------------
-- security invoker: respeta RLS, solo devuelve tableros a los que tengo acceso

create or replace function public.finance_boards_overview(p_month_start date default date_trunc('month', current_date)::date)
returns table (
  id bigint,
  title text,
  description text,
  color text,
  initial_balance numeric,
  user_id uuid,
  is_owner boolean,
  created_at timestamptz,
  balance numeric,
  month_income numeric,
  month_expense numeric,
  tx_count bigint,
  shared_count bigint
)
language sql
stable
set search_path = public
as $$
  select
    b.id,
    b.title,
    b.description,
    b.color,
    b.initial_balance,
    b.user_id,
    b.user_id = auth.uid() as is_owner,
    b.created_at,
    b.initial_balance
      + coalesce(sum(case when t.type = 'income' then t.amount else 0 end), 0)
      - coalesce(sum(case when t.type = 'expense' then t.amount else 0 end), 0) as balance,
    coalesce(sum(case when t.type = 'income' and t.date >= p_month_start
      and t.date < (p_month_start + interval '1 month') then t.amount else 0 end), 0) as month_income,
    coalesce(sum(case when t.type = 'expense' and t.date >= p_month_start
      and t.date < (p_month_start + interval '1 month') then t.amount else 0 end), 0) as month_expense,
    count(t.id) as tx_count,
    (select count(*) from public.finance_board_shares s where s.board_id = b.id) as shared_count
  from public.finance_boards b
  left join public.finance_transactions t on t.board_id = b.id
  group by b.id
  order by b.created_at asc;
$$;

grant execute on function public.finance_boards_overview(date) to authenticated;

-- 5) Miembros de un tablero con nombre (para "registrado por") --------------

create or replace function public.finance_board_members(p_board_id bigint)
returns table (user_id uuid, email text, display_name text, is_owner boolean)
language sql
stable
security definer
set search_path = public
as $$
  select p.id, p.email,
         coalesce(nullif(trim(p.display_name), ''), split_part(p.email, '@', 1)),
         true
  from public.finance_boards b
  join public.profiles p on p.id = b.user_id
  where b.id = p_board_id and public.finance_can_access_board(p_board_id)
  union all
  select p.id, p.email,
         coalesce(nullif(trim(p.display_name), ''), split_part(p.email, '@', 1)),
         false
  from public.finance_board_shares s
  join public.profiles p on p.id = s.shared_with
  where s.board_id = p_board_id and public.finance_can_access_board(p_board_id);
$$;

grant execute on function public.finance_board_members(bigint) to authenticated;
