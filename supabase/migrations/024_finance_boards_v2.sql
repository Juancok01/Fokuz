-- 1) Columnas nuevas ---------------------------------------------------------

alter table public.finance_boards
  alter column user_id set default auth.uid(),
  add column if not exists color text not null default '#00DF81',
  add column if not exists initial_balance numeric(15, 2) not null default 0;

alter table public.finance_categories
  add column if not exists icon text,
  add column if not exists sort_order int not null default 0;

alter table public.finance_transactions
  add column if not exists payment_method text,           -- 'efectivo' | 'digital' | 'tarjeta' | null
  add column if not exists created_by uuid default auth.uid() references auth.users (id) on delete set null;

create index if not exists finance_transactions_board_date_idx
  on public.finance_transactions (board_id, date desc);
create index if not exists finance_categories_board_idx
  on public.finance_categories (board_id);

-- 2) Compartir tableros ------------------------------------------------------

create table if not exists public.finance_board_shares (
  id bigint generated by default as identity primary key,
  board_id bigint not null references public.finance_boards (id) on delete cascade,
  shared_with uuid not null references public.profiles (id) on delete cascade,
  shared_by uuid not null references public.profiles (id) on delete cascade default auth.uid(),
  created_at timestamptz not null default now(),
  constraint finance_board_shares_unique unique (board_id, shared_with),
  constraint finance_board_shares_not_self check (shared_with <> shared_by)
);

create index if not exists finance_board_shares_board_idx on public.finance_board_shares (board_id);
create index if not exists finance_board_shares_with_idx on public.finance_board_shares (shared_with);

alter table public.finance_board_shares enable row level security;

-- Helpers (security definer → evitan recursión de RLS)
create or replace function public.finance_is_board_owner(p_board_id bigint)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.finance_boards b
    where b.id = p_board_id and b.user_id = auth.uid()
  );
$$;

create or replace function public.finance_can_access_board(p_board_id bigint)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.finance_boards b
    where b.id = p_board_id and b.user_id = auth.uid()
  ) or exists (
    select 1 from public.finance_board_shares s
    where s.board_id = p_board_id and s.shared_with = auth.uid()
  );
$$;

grant execute on function public.finance_is_board_owner(bigint) to authenticated;
grant execute on function public.finance_can_access_board(bigint) to authenticated;

-- 3) Políticas RLS -----------------------------------------------------------

-- Tableros: el dueño hace todo; los compartidos pueden verlos
drop policy if exists "Users can manage their own finance boards" on public.finance_boards;
drop policy if exists "finance_boards_select" on public.finance_boards;
drop policy if exists "finance_boards_insert" on public.finance_boards;
drop policy if exists "finance_boards_update" on public.finance_boards;
drop policy if exists "finance_boards_delete" on public.finance_boards;

create policy "finance_boards_select" on public.finance_boards for select
  using (public.finance_can_access_board(id));
create policy "finance_boards_insert" on public.finance_boards for insert
  with check (auth.uid() = user_id);
create policy "finance_boards_update" on public.finance_boards for update
  using (auth.uid() = user_id) with check (auth.uid() = user_id);
create policy "finance_boards_delete" on public.finance_boards for delete
  using (auth.uid() = user_id);

-- Compartidos: los ven dueño e invitados; solo el dueño agrega;
-- el dueño puede quitar a cualquiera y el invitado puede salirse
drop policy if exists "finance_board_shares_select" on public.finance_board_shares;
drop policy if exists "finance_board_shares_insert" on public.finance_board_shares;
drop policy if exists "finance_board_shares_delete" on public.finance_board_shares;

create policy "finance_board_shares_select" on public.finance_board_shares for select
  using (public.finance_can_access_board(board_id));
create policy "finance_board_shares_insert" on public.finance_board_shares for insert
  with check (auth.uid() = shared_by and public.finance_is_board_owner(board_id));
create policy "finance_board_shares_delete" on public.finance_board_shares for delete
  using (public.finance_is_board_owner(board_id) or auth.uid() = shared_with);

-- Cuentas, categorías y movimientos: cualquiera con acceso al tablero
drop policy if exists "Users can manage accounts of their boards" on public.finance_accounts;
